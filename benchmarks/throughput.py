"""Measure throughput: diagnostics and bytes per second on inputs of known size.

Runs the checker against the fixtures in `benchmarks/fixtures/` and reports:

    - wall-clock seconds per fixture
    - bytes of source processed per second
    - diagnostics produced per second
    - the number of diagnostics the fixture is expected to contain

The fixtures are generated by `scripts/generate_benchmark_fixtures.py` and
committed to git, so their sizes are stable across runs. That stability is
what makes the numbers comparable.

Requires the bundled tsgo binary. `benchmarks/run.py` checks for it before
calling `run()`; if you invoke this module directly, expect an
`CompilerNotFoundError` when the binary is missing.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path

FIXTURES = Path(__file__).resolve().parent / "fixtures"


# The fixtures to measure, in increasing order of size.
STANDALONE_FIXTURES: list[str] = [
    "tiny.ts",
    "medium.ts",
    "large.ts",
    "errors-100.ts",
    "errors-1000.ts",
    "mixed.ts",
]


# ---------------------------------------------------------------------------
# Measurement
# ---------------------------------------------------------------------------


@dataclass
class FixtureMeasurement:
    name: str
    elapsed_seconds: float = 0.0
    diagnostics: int = 0
    source_bytes: int = 0
    bytes_per_second: float = 0.0
    diagnostics_per_second: float = 0.0
    error: str = ""

    def as_dict(self) -> dict:
        if self.error:
            return {"error": self.error}
        return {
            "elapsed_seconds": self.elapsed_seconds,
            "diagnostics": self.diagnostics,
            "source_bytes": self.source_bytes,
            "bytes_per_second": self.bytes_per_second,
            "diagnostics_per_second": self.diagnostics_per_second,
        }


def _time_file(path: Path) -> FixtureMeasurement:
    """Run one check and record its timing and diagnostic count."""
    from pytscheck import check_file

    if not path.exists():
        return FixtureMeasurement(name=path.name, error=f"fixture not found: {path.name}")

    try:
        size = path.stat().st_size
    except OSError as exc:
        return FixtureMeasurement(name=path.name, error=f"stat failed: {exc}")

    # Warm up once so we measure steady-state, not first-call cost.
    # The warmup uses the same file; if it fails, the timed run will too.
    try:
        check_file(path)
    except Exception as exc:
        return FixtureMeasurement(name=path.name, error=f"{type(exc).__name__}: {exc}")

    t0 = time.perf_counter()
    try:
        result = check_file(path)
    except Exception as exc:
        return FixtureMeasurement(name=path.name, error=f"{type(exc).__name__}: {exc}")
    elapsed = time.perf_counter() - t0

    n_diags = len(result.diagnostics)
    return FixtureMeasurement(
        name=path.name,
        elapsed_seconds=elapsed,
        diagnostics=n_diags,
        source_bytes=size,
        bytes_per_second=size / elapsed if elapsed > 0 else 0.0,
        diagnostics_per_second=n_diags / elapsed if elapsed > 0 else 0.0,
    )


def _time_project(project_dir: Path) -> FixtureMeasurement:
    """Run a project check and record its timing and diagnostic count."""
    from pytscheck import check_project

    if not project_dir.is_dir():
        return FixtureMeasurement(
            name=project_dir.name,
            error=f"project not found: {project_dir.name}",
        )

    tsconfig = project_dir / "tsconfig.json"
    if not tsconfig.exists():
        return FixtureMeasurement(
            name=project_dir.name,
            error=f"no tsconfig.json in {project_dir.name}",
        )

    ts_files = list(project_dir.rglob("*.ts"))
    if not ts_files:
        return FixtureMeasurement(
            name=project_dir.name,
            error=f"no .ts files in {project_dir.name}",
        )

    try:
        total_bytes = sum(f.stat().st_size for f in ts_files)
    except OSError as exc:
        return FixtureMeasurement(name=project_dir.name, error=f"stat failed: {exc}")

    # Warmup
    try:
        check_project(project_dir)
    except Exception as exc:
        return FixtureMeasurement(name=project_dir.name, error=f"{type(exc).__name__}: {exc}")

    t0 = time.perf_counter()
    try:
        result = check_project(project_dir)
    except Exception as exc:
        return FixtureMeasurement(name=project_dir.name, error=f"{type(exc).__name__}: {exc}")
    elapsed = time.perf_counter() - t0

    n_diags = len(result.diagnostics)
    measurement = FixtureMeasurement(
        name=project_dir.name,
        elapsed_seconds=elapsed,
        diagnostics=n_diags,
        source_bytes=total_bytes,
        bytes_per_second=total_bytes / elapsed if elapsed > 0 else 0.0,
        diagnostics_per_second=n_diags / elapsed if elapsed > 0 else 0.0,
    )
    # Attach project-specific fields by extending the returned dict at the
    # call site, not here; the shape stays uniform.
    return measurement


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def run() -> dict:
    """Run the throughput benchmark and return a results dict.

    Called by `benchmarks/run.py`. Return shape:

        {
            "tiny.ts": {"elapsed_seconds": ..., "diagnostics": ..., ...},
            "medium.ts": {...},
            ...
            "large-project": {"elapsed_seconds": ..., "files": N, ...},
        }
    """
    data: dict = {}

    # Standalone files
    for name in STANDALONE_FIXTURES:
        measurement = _time_file(FIXTURES / name)
        data[name] = measurement.as_dict()

    # Project
    project = FIXTURES / "large-project"
    if project.is_dir() and (project / "tsconfig.json").exists():
        ts_files = list(project.rglob("*.ts"))
        measurement = _time_project(project)
        project_data = measurement.as_dict()
        if "error" not in project_data:
            project_data["files"] = len(ts_files)
            project_data["files_per_second"] = (
                len(ts_files) / measurement.elapsed_seconds
                if measurement.elapsed_seconds > 0
                else 0.0
            )
        data["large-project"] = project_data

    return data
